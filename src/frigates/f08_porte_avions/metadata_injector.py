    print(f"\n🔧 Test rapport de variation:")
    for intensity in ["subtle", "moderate", "aggressive"]:
        report = injector.get_variation_report(intensity)
        print(f"   {intensity}: ID={report['unique_id']}")
    
    print("\n✅ Module metadata_injector.py fonctionnel")
